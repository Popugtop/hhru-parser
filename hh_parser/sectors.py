"""Классификация сектора работодателя (бюджетный / коммерческий) по названию.

Эвристика по организационно-правовым формам и ключевым словам, упомянутым
в задаче (МАОУ, МБОУ, МАДОУ, ГБУЗ, ГАУЗ, ГАПОУ, ФГБУ, ФГАОУ, «администрация»,
«департамент», «министерство», «государственн», «муниципальн»), расширенная
другими распространёнными формами бюджетных организаций (МБУ, МКУ, МАУ, ГКУ,
ГБУ, ГАУ, МБДОУ, ГБПОУ, ФГБОУ) — это приближение, не точная сверка по ИНН/ОПФ;
сложные случаи дополнительно сверяются через фильтр industry=36 на этапе сбора.
"""
from __future__ import annotations

import re

_BUDGET_ABBREVIATIONS = (
    "МАОУ", "МБОУ", "МАДОУ", "МБДОУ",
    "ГБУЗ", "ГАУЗ", "ГАПОУ", "ГБПОУ",
    "ФГБУ", "ФГАОУ", "ФГБОУ",
    "МБУ", "МКУ", "МАУ", "ГКУ", "ГБУ", "ГАУ",
)

_BUDGET_KEYWORDS = (
    "администрац",
    "департамент",
    "министерств",
    "государственн",
    "муниципальн",
)

_ABBR_PATTERN = r"|".join(rf"\b{abbr}\b" for abbr in _BUDGET_ABBREVIATIONS)
_KEYWORD_PATTERN = r"|".join(_BUDGET_KEYWORDS)
_BUDGET_RE = re.compile(f"({_ABBR_PATTERN}|{_KEYWORD_PATTERN})", re.IGNORECASE)

BUDGET = "бюджетный"
COMMERCIAL = "коммерческий"


def classify_sector(employer_name: str | None) -> str:
    """"бюджетный", если название работодателя содержит признаки
    государственного/муниципального учреждения, иначе "коммерческий"."""
    if not employer_name:
        return COMMERCIAL
    return BUDGET if _BUDGET_RE.search(employer_name) else COMMERCIAL
